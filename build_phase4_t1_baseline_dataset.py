from __future__ import annotations

from pathlib import Path

import pandas as pd


ROOT = Path(__file__).parent
SOURCE_DIR = ROOT / "output/analysis_candidates/phase2_feature_extraction/all_t1_patients_selected_features"
OUT_DIR = ROOT / "output/analysis_candidates/phase4_t1_baseline"

WIDE_PATH = SOURCE_DIR / "phase2_all_t1_selected_features_wide.csv"
STATUS_PATH = SOURCE_DIR / "phase2_all_t1_selected_features_patient_table_status.csv"
SELECTED_PATH = ROOT / "phase2_selected_features.csv"

DATASET_PATH = OUT_DIR / "phase4_t1_baseline_patient_dataset.csv"
METADATA_PATH = OUT_DIR / "phase4_t1_baseline_feature_metadata.csv"
MISSINGNESS_PATH = OUT_DIR / "phase4_t1_baseline_missingness_summary.csv"
TABLE_COVERAGE_PATH = OUT_DIR / "phase4_t1_baseline_table_coverage.csv"
README_PATH = OUT_DIR / "README_phase4_t1_baseline_dataset.md"

ADJUSTED_TABLES = {"barometer", "significant", "sensor_linear_accelerometer"}


def window_class(table_name: str) -> str:
    return "adjusted_first_available_7d" if table_name in ADJUSTED_TABLES else "t1_week_first_valid_24h"


def build_readme(dataset: pd.DataFrame, metadata: pd.DataFrame, status: pd.DataFrame) -> str:
    strict = int((metadata["primary_model_recommendation"] == "include_primary").sum())
    adjusted = int((metadata["primary_model_recommendation"] == "adjusted_sensitivity").sum())
    low_coverage = int((metadata["primary_model_recommendation"] == "coverage_sensitivity").sum())
    no_observed = int((metadata["primary_model_recommendation"] == "exclude_no_observed_data").sum())
    calculated_blocks = int(status["table_status"].astype(str).eq("calculated").sum())
    return f"""# Phase 4 T1 Baseline Dataset

Generated by `build_phase4_t1_baseline_dataset.py`.

## Scope

- Patients: `{dataset['Subject_ID_D'].nunique()}`.
- Selected feature columns: `{len(metadata)}`.
- Primary-model T1-week features: `{strict}`.
- Adjusted first-available features retained for sensitivity analysis: `{adjusted}`.
- Low-coverage T1-week features retained for sensitivity analysis: `{low_coverage}`.
- Features excluded because no patient had an observed value: `{no_observed}`.
- Calculated patient-table blocks in the source extraction: `{calculated_blocks}`.

## Protocol

The source extraction uses the preferred day-after-T1 24-hour window when available, then the first valid 24-hour span within the T1 week. The resulting window rule is retained in the source status table. Barometer, significant-motion, and sensor-linear-accelerometer features use an adjusted first-available 7-day protocol and are labeled sensitivity-only here.

## Missingness

Feature values are preserved as observed or missing. The dataset includes `missing__<feature>` indicators and patient/table coverage summaries. Missing values do not mean zero activity.

For modeling, use fold-fitted median imputation plus missingness indicators. Do not calculate imputation medians from the full dataset before cross-validation.

## Files

- `phase4_t1_baseline_patient_dataset.csv`: patient-level baseline values and coverage summaries.
- `phase4_t1_baseline_feature_metadata.csv`: feature provenance and model inclusion recommendation.
- `phase4_t1_baseline_missingness_summary.csv`: feature-level observed/missingness summary.
- `phase4_t1_baseline_table_coverage.csv`: table-level window and coverage summary.

This is a proof-of-concept analysis dataset, not a final validated biomarker table.
"""


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    wide = pd.read_csv(WIDE_PATH, dtype={"Subject_ID_D": str, "Subject_ID_N": str})
    selected = pd.read_csv(SELECTED_PATH, dtype=str)
    status = pd.read_csv(STATUS_PATH, dtype=str)

    feature_names = [name for name in selected["feature_name"].dropna().unique() if name in wide.columns]
    metadata = selected[selected["feature_name"].isin(feature_names)].drop_duplicates("feature_name").copy()
    metadata["window_class"] = metadata["source_table"].map(window_class)
    metadata["primary_model_recommendation"] = metadata["window_class"].map(
        {"t1_week_first_valid_24h": "include_primary", "adjusted_first_available_7d": "adjusted_sensitivity"}
    )
    metadata["source_column"] = metadata["feature_name"]
    metadata = metadata[
        [
            "source_table",
            "feature_name",
            "feature_family",
            "short_description",
            "selection_reason",
            "privacy_note",
            "selected_date",
            "window_class",
            "primary_model_recommendation",
            "source_column",
        ]
    ].sort_values(["window_class", "source_table", "feature_name"])

    dataset = wide.copy()
    feature_values = dataset[feature_names].apply(pd.to_numeric, errors="coerce")
    missing_indicators = feature_values.isna().astype("int8").add_prefix("missing__")
    missing_indicators.columns = [f"missing__{name}" for name in feature_names]
    dataset = pd.concat([dataset.drop(columns=feature_names), feature_values, missing_indicators], axis=1)
    for feature in feature_names:
        dataset[feature] = feature_values[feature]

    feature_missing = feature_values.isna()
    dataset["baseline_feature_count_total"] = len(feature_names)
    dataset["baseline_feature_count_observed"] = (~feature_missing).sum(axis=1)
    dataset["baseline_feature_missing_fraction"] = feature_missing.mean(axis=1)

    table_summary = (
        status.assign(
            calculated=status["table_status"].astype(str).eq("calculated"),
            window_class=status["table_name"].map(window_class),
        )
        .groupby("Subject_ID_D", dropna=False)
        .agg(
            baseline_tables_calculated=("calculated", "sum"),
            baseline_tables_total=("table_name", "nunique"),
            t1_week_tables_calculated=("calculated", lambda x: int(x[status.loc[x.index, "table_name"].map(window_class).eq("t1_week_first_valid_24h")].sum())),
            adjusted_tables_calculated=("calculated", lambda x: int(x[status.loc[x.index, "table_name"].map(window_class).eq("adjusted_first_available_7d")].sum())),
        )
        .reset_index()
    )
    table_summary["baseline_table_coverage_fraction"] = (
        table_summary["baseline_tables_calculated"] / table_summary["baseline_tables_total"]
    )
    dataset = dataset.merge(table_summary, on="Subject_ID_D", how="left")
    dataset["phase4_protocol"] = "exploratory_first_valid_24h_after_T1_within_T1_week"
    dataset["phase4_primary_model_scope"] = "strict_and_fallback_T1_week_features_only"
    dataset["raw_source_wide"] = str(WIDE_PATH.relative_to(ROOT))

    missingness = metadata[["source_table", "feature_name", "feature_family", "window_class", "primary_model_recommendation"]].copy()
    missingness["n_patients"] = len(dataset)
    missingness["n_observed"] = [int(dataset[name].notna().sum()) for name in metadata["feature_name"]]
    missingness["n_missing"] = missingness["n_patients"] - missingness["n_observed"]
    missingness["missing_percent"] = (100 * missingness["n_missing"] / missingness["n_patients"]).round(1)
    missingness = missingness.sort_values(["missing_percent", "source_table", "feature_name"], ascending=[False, True, True])
    missing_by_feature = missingness.set_index("feature_name")["missing_percent"]
    metadata["missing_percent"] = metadata["feature_name"].map(missing_by_feature)
    metadata.loc[metadata["window_class"] == "adjusted_first_available_7d", "primary_model_recommendation"] = "adjusted_sensitivity"
    metadata.loc[
        (metadata["window_class"] == "t1_week_first_valid_24h") & (metadata["missing_percent"] > 50),
        "primary_model_recommendation",
    ] = "coverage_sensitivity"
    metadata.loc[metadata["missing_percent"] >= 100, "primary_model_recommendation"] = "exclude_no_observed_data"
    recommendation_by_feature = metadata.set_index("feature_name")["primary_model_recommendation"]
    missingness["primary_model_recommendation"] = missingness["feature_name"].map(recommendation_by_feature)

    status_out = status.copy()
    status_out["window_class"] = status_out["table_name"].map(window_class)
    status_out["is_calculated"] = status_out["table_status"].astype(str).eq("calculated").astype("int8")
    status_out.to_csv(TABLE_COVERAGE_PATH, index=False)
    dataset.to_csv(DATASET_PATH, index=False)
    metadata.to_csv(METADATA_PATH, index=False)
    missingness.to_csv(MISSINGNESS_PATH, index=False)
    README_PATH.write_text(build_readme(dataset, metadata, status), encoding="utf-8")

    print(f"patients: {len(dataset)}")
    print(f"features: {len(feature_names)}")
    print(f"primary_model_features: {int((metadata['primary_model_recommendation'] == 'include_primary').sum())}")
    print(f"sensitivity_features: {int((metadata['primary_model_recommendation'] != 'include_primary').sum())}")
    print(f"outputs: {OUT_DIR}")


if __name__ == "__main__":
    main()
